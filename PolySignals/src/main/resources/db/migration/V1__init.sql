CREATE TABLE bet
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    whale_id         BIGINT                                  NOT NULL,
    market_id        VARCHAR(128)                            NOT NULL,
    outcome          VARCHAR(255)                            NOT NULL,
    amount           DECIMAL(19, 8)                          NOT NULL,
    transaction_hash VARCHAR(128),
    transaction_time TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    created_at       TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    unique_key       VARCHAR(256)                            NOT NULL,
    CONSTRAINT pk_bet PRIMARY KEY (id)
);

CREATE TABLE signal
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    market_id        VARCHAR(128)                            NOT NULL,
    market_question  TEXT,
    market_url       VARCHAR(1024),
    outcome          VARCHAR(255)                            NOT NULL,
    whales_count     INTEGER                                 NOT NULL,
    total_amount     DECIMAL(19, 8)                          NOT NULL,
    period_hours     INTEGER                                 NOT NULL,
    first_bet_at     TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    last_bet_at      TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    telegram_sent    BOOLEAN                                 NOT NULL DEFAULT FALSE,
    telegram_sent_at TIMESTAMP WITHOUT TIME ZONE,
    reason           TEXT,
    created_at       TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_signal PRIMARY KEY (id)
);

CREATE TABLE whale
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id      VARCHAR(128)                            NOT NULL,
    user_name    VARCHAR(255),
    volume       DECIMAL,
    profit       DECIMAL,
    last_seen_at TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_whale PRIMARY KEY (id)
);

ALTER TABLE bet
