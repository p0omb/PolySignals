ALTER TABLE whale
    ADD CONSTRAINT uc_whale_user UNIQUE (user_id);

CREATE INDEX idx_bet_market_outcome_time ON bet (market_id, outcome, transaction_time);
CREATE INDEX idx_signal_market_outcome_time ON signal (market_id, outcome, created_at);
